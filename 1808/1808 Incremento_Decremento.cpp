#include <stdio.h>
#include <stdlib.h>

//Contagem regressiva de 10 a 0 e lançar!


// i++ // i = i + 1 /incremento
// i-- // i = i - 1 /decremento

int main(){
	
	
	int I;
	
	for(I=10; I >= 1; I--){
		
		printf("%d \n", I);
		
	}
	

	printf("Lancar!!!");
	
	system("pause");
	return 0;
	
}
